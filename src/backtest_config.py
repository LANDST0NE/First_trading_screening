"""
Параметры и настройки модуля исторического тестирования (Backtesting Engine).
Все параметры исполнения, комиссий, проскальзывания и консервативных правил собраны здесь.
"""

from dataclasses import dataclass


@dataclass
class BacktestConfig:
    # 1. Стартовый капитал и базовые торговые параметры
    initial_capital: float = 100_000.0       # Стартовый депозит в рублях
    fixed_risk_per_trade: float = 1_000.0    # Базовый риск на сделку в рублях (1.0% от 100k)
    max_daily_loss: float = 2_000.0          # Дневной лимит потерь (2R)

    # 2. Комиссии брокера и биржи (Мосбиржа TQBR)
    # По умолчанию: 0.05% за каждую сторону (открытие и закрытие)
    commission_entry_rate: float = 0.0005    # 0.05% при входе
    commission_exit_rate: float = 0.0005     # 0.05% при выходе

    # 3. Проскальзывание (Slippage)
    # Консервативное моделирование неблагоприятного исполнения
    slippage_limit_entry_pct: float = 0.0000 # Лимитные ордера в стакане не имеют отрицательного проскальзывания
    slippage_market_take_pct: float = 0.0002 # 0.02% при исполнении лимитного тейка в моменте
    slippage_stop_loss_pct: float = 0.0005   # 0.05% при срабатывании стопа (рыночный сброс на импульсе)
    slippage_gap_pct: float = 0.0003         # 0.03% дополнительное проскальзывание при исполнении на гэпе

    # 4. Модель исполнения лимитных заявок
    # Срок действия лимитных заявок (Time-In-Force)
    limit_expiry_bars: int = 3               # Лимитки Entry1 / Entry2 живут ровно 3 часовых свечи после сигнала
    
    # Требование к пробитию уровня (Penetration Rule)
    # Требовать проход цены сквозь уровень минимум на 1 шаг цены,
    # либо закрытие свечи на/за уровнем. Простое касание верхнего края тени не исполняет заявку.
    min_penetration_ticks: int = 1

    # 5. Консервативные правила разрешения конфликтов внутри одной OHLCV-свечи
    # Правило 1: Если на одной свече одновременно достигаются Entry и Stop-Loss -> Стоп сработал первым, вход отменяется
    assume_stop_before_entry_on_same_bar: bool = True

    # Правило 2: Если на одной свече одновременно достигаются Entry 2 и TP1 -> TP1 взят первым, Entry 2 отменяется
    assume_tp_before_entry2_on_same_bar: bool = True

    # Правило 3: Если на одной свече одновременно задеты Stop-Loss и TP -> Сначала сработал Stop-Loss (наихудший исход)
    assume_stop_before_tp_on_same_bar: bool = True

    # Правило 4: Отмена Entry 2 сразу после фиксации Take 1 (не добирать позицию после взятия первой цели)
    cancel_entry2_on_tp1: bool = True


# Дефолтный синглтон конфигурации для удобного импорта
DEFAULT_BACKTEST_CONFIG = BacktestConfig()
